package entity;

public class PhieuDoiTra {
    private String maPhieuDoiTra;
    private String maHoaDon;
    private String lyDoDoiTra;
    private String hinhThucXuLy;

    public PhieuDoiTra() {
    }

    public String getMaPhieuDoiTra() { return maPhieuDoiTra; }
    public void setMaPhieuDoiTra(String maPhieuDoiTra) { this.maPhieuDoiTra = maPhieuDoiTra; }
    public String getMaHoaDon() { return maHoaDon; }
    public void setMaHoaDon(String maHoaDon) { this.maHoaDon = maHoaDon; }
    public String getLyDoDoiTra() { return lyDoDoiTra; }
    public void setLyDoDoiTra(String lyDoDoiTra) { this.lyDoDoiTra = lyDoDoiTra; }
    public String getHinhThucXuLy() { return hinhThucXuLy; }
    public void setHinhThucXuLy(String hinhThucXuLy) { this.hinhThucXuLy = hinhThucXuLy; }
}
